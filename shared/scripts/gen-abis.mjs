// Generates src/generated/abis.ts from the compiled hardhat artifacts, so the bot and the
// Mini App always use the exact ABIs of the deployed contracts. Run after `hardhat compile`.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const build = path.join(here, "../../contracts/build/contracts")

const keel = {
  keelGuardianAbi: "keel/KeelGuardian.sol/KeelGuardian.json",
  keelGuardianFactoryAbi: "keel/KeelGuardianFactory.sol/KeelGuardianFactory.json",
  keelPayAbi: "keel/KeelPay.sol/KeelPay.json",
}

// For MUSD contracts only keep what Keel touches (keeps the bundle small).
const musd = {
  troveManagerAbi: ["TroveManager.sol/TroveManager.json", [
    "getCurrentICR","getEntireDebtAndColl","getTroveStatus","getTroveInterestRate","getTCR",
    "checkRecoveryMode","getTroveOwnersCount","getTroveFromTroveOwnersArray","MUSD_GAS_COMPENSATION",
    "MCR","CCR","getTroveColl","getTroveDebt","getNominalICR","redeemCollateral","Redemption","Liquidation","TroveLiquidated",
  ]],
  borrowerOperationsAbi: ["BorrowerOperations.sol/BorrowerOperations.json", [
    "openTrove","addColl","withdrawColl","withdrawMUSD","repayMUSD","closeTrove","refinance","adjustTrove",
    "getBorrowingFee","minNetDebt","borrowingRate","refinancingFeePercentage","claimCollateral","TroveUpdated","TroveCreated",
  ]],
  priceFeedAbi: ["PriceFeed.sol/PriceFeed.json", ["fetchPrice"]],
  hintHelpersAbi: ["HintHelpers.sol/HintHelpers.json", ["computeNominalCR","computeCR","getApproxHint","getRedemptionHints"]],
  sortedTrovesAbi: ["SortedTroves.sol/SortedTroves.json", ["findInsertPosition","getFirst","getLast","getNext","getPrev","getSize","contains"]],
  interestRateManagerAbi: ["InterestRateManager.sol/InterestRateManager.json", ["interestRate"]],
  stabilityPoolAbi: ["StabilityPool.sol/StabilityPool.json", ["getTotalMUSDDeposits","getCollateralBalance"]],
  musdAbi: ["token/MUSD.sol/MUSD.json", [
    "name","symbol","decimals","totalSupply","balanceOf","allowance","approve","transfer","transferFrom",
    "permit","nonces","DOMAIN_SEPARATOR","Transfer","Approval",
  ]],
}

const load = (rel) => JSON.parse(fs.readFileSync(path.join(build, rel), "utf8")).abi
let out = "// AUTO-GENERATED by scripts/gen-abis.mjs - do not edit.\n"
for (const [name, rel] of Object.entries(keel)) {
  out += `export const ${name} = ${JSON.stringify(load(rel))} as const\n`
}
for (const [name, [rel, keep]] of Object.entries(musd)) {
  const abi = load(rel).filter((e) => e.type === "function" || e.type === "event" ? keep.includes(e.name) : false)
  const missing = keep.filter((k) => !abi.some((e) => e.name === k))
  if (missing.length) throw new Error(`${name}: missing ${missing.join(", ")}`)
  out += `export const ${name} = ${JSON.stringify(abi)} as const\n`
}
fs.writeFileSync(path.join(here, "../src/generated/abis.ts"), out)
console.log("wrote src/generated/abis.ts")
